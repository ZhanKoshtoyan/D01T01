#!/bin/bash

# Пользователь должен ввести ./src/edit.sh src/TextFile.txt Hom home, где:
#$0 = ./src/edit.sh;
#$1 = src/TextFile.txt;
#$2 = Hom;
#$3 = home;

# Краевая ситуация 1: Проверка что количество переданных аргументов равно 3.
if [ "$#" -ne 3 ]; then
    echo "Использование: $0 <файл> <что_искать> <на_что_заменить>"
    exit 1
fi

# Краевая ситуация 2: Проверка существования файла
if [ ! -f "$1" ]; then
    echo "Ошибка: Файл  не существует!"
    exit 1
fi

# Краевая ситуация 3: Проверка, есть ли вообще этот текст в файле
# grep = ищет строку в файле
# -q = заставляет ничего не выводить на экран и вернуть статус 0 или 1
if ! grep -q "$2" "$1"; then
    echo "Текст  не найден в файле. Изменения не требуются."
    exit 0
fi

# Основная логика (выполняется только если прошлые проверки пройдены)
# sed = потоковый текстовый редактор
# -i = редактирование прямо внутри файла, без создания копий
# g = заменить все вхождения, а не только первое
sed -i "s|$2|$3|g" "$1"

# Сбор данных и логирование
FILE_SIZE=$(stat -c %s "$1")
CURRENT_TIME=$(date "+%Y-%m-%d %H:%M")
SHA_SUM=$(sha256sum "$1" | awk '{print $1}')

echo "$1 - $FILE_SIZE - $CURRENT_TIME - $SHA_SUM - sha256" >> src/files.log
echo "Успешно изменено и залогировано!"

